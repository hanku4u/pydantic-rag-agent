"""Tests for the PDF loader.

The fixture is generated by ``tests/fixtures/pdf_builder.py`` rather than committed:
a two-page PDF written inline is reviewable, and an opaque binary blob is not. The
builder is itself exercised here by the loader parsing its output.
"""

from __future__ import annotations

import hashlib
from io import BytesIO
from pathlib import Path

import pypdfium2 as pdfium
import pytest
from fixtures.pdf_builder import build_pdf_with_image, build_text_pdf
from PIL import Image

from pydantic_rag_agent.adapters.loaders.pdf import PdfLoader

DOCUMENT_ID = "c" * 64


def write_pdf(directory: Path, name: str, pages: list[str], *, title: str | None = None) -> Path:
    path = directory / name
    path.write_bytes(build_text_pdf(pages, title=title))
    return path


def pdf_loader_should_declare_the_pdf_suffix() -> None:
    # given / when / then: format discovery comes from the loader, not a hard-coded list
    assert PdfLoader().suffixes == frozenset({".pdf"})


def pdf_loader_with_multiple_pages_should_create_one_block_per_page(tmp_path: Path) -> None:
    # given: a two-page PDF
    path = write_pdf(tmp_path, "handbook.pdf", ["Page one text.", "Page two text."])

    # when: it is loaded
    document = PdfLoader().load(path, document_id=DOCUMENT_ID)

    # then: each page is a block, numbered from one so citations read correctly
    assert [block.page for block in document.blocks] == [1, 2]
    assert "Page one text." in document.blocks[0].text
    assert "Page two text." in document.blocks[1].text


def pdf_loader_should_use_the_document_title_when_present(tmp_path: Path) -> None:
    # given: a PDF carrying its own title metadata
    path = write_pdf(tmp_path, "file-name.pdf", ["text"], title="Operations Handbook")

    # when / then: the embedded title beats the filename, which is often a hash
    assert PdfLoader().load(path, document_id=DOCUMENT_ID).title == "Operations Handbook"


def pdf_loader_without_title_metadata_should_fall_back_to_the_filename(tmp_path: Path) -> None:
    # given: a PDF with no title metadata
    path = write_pdf(tmp_path, "quarterly-report.pdf", ["text"])

    # when / then: the filename is better than no title at all
    assert PdfLoader().load(path, document_id=DOCUMENT_ID).title == "quarterly-report"


def pdf_loader_with_a_page_that_has_no_text_should_skip_that_page(tmp_path: Path) -> None:
    # given: a PDF whose second page is blank
    path = write_pdf(tmp_path, "sparse.pdf", ["First page.", ""])

    # when: it is loaded
    document = PdfLoader().load(path, document_id=DOCUMENT_ID)

    # then: no empty block is produced, and real pages keep their real numbers
    assert len(document.blocks) == 1
    assert document.blocks[0].page == 1


def pdf_loader_should_normalise_line_endings(tmp_path: Path) -> None:
    # given: a page with two lines, which PDFium reports with CRLF
    path = write_pdf(tmp_path, "lines.pdf", ["first line\nsecond line"])

    # when: it is loaded
    text = PdfLoader().load(path, document_id=DOCUMENT_ID).blocks[0].text

    # then: the chunker only ever sees "\n", so paragraph splitting is consistent
    assert "\r" not in text
    assert "first line" in text and "second line" in text


def pdf_loader_with_a_corrupt_file_should_raise(tmp_path: Path) -> None:
    # given: a file that is not a PDF at all
    path = tmp_path / "broken.pdf"
    path.write_bytes(b"this is not a PDF")

    # when / then: the loader raises, and the pipeline reports it per file
    with pytest.raises(pdfium.PdfiumError):
        PdfLoader().load(path, document_id=DOCUMENT_ID)


def pdf_loader_should_report_the_pdf_media_type(tmp_path: Path) -> None:
    # given: a valid PDF
    path = write_pdf(tmp_path, "doc.pdf", ["text"])

    # when / then: the media type travels with the document
    assert PdfLoader().load(path, document_id=DOCUMENT_ID).media_type == "application/pdf"


def pdf_loader_with_an_embedded_image_should_extract_it(tmp_path: Path) -> None:
    # given: a page containing a JPEG
    buffer = BytesIO()
    Image.new("RGB", (48, 32), "teal").save(buffer, format="JPEG")
    path = tmp_path / "illustrated.pdf"
    path.write_bytes(
        build_pdf_with_image(
            "A page with a diagram.",
            jpeg=buffer.getvalue(),
            width=48,
            height=32,
        )
    )

    # when: the PDF is loaded
    document = PdfLoader().load(path, document_id=DOCUMENT_ID)

    # then: the image is surfaced with page context and a usable PNG
    assert len(document.images) == 1
    image = document.images[0]
    assert image.media_type == "image/png"
    assert image.page == 1
    assert image.image_id == hashlib.sha256(image.data).hexdigest()
    assert Image.open(BytesIO(image.data)).size == (48, 32)


def pdf_loader_without_images_should_return_no_images(tmp_path: Path) -> None:
    # given: a text-only PDF
    path = write_pdf(tmp_path, "plain.pdf", ["just text"])

    # when / then: nothing is invented
    assert PdfLoader().load(path, document_id=DOCUMENT_ID).images == ()
